export function getSongOfRestDie(level) {
  const numericLevel = Number(level);
  if (numericLevel >= 17) return "1к12";
  if (numericLevel >= 13) return "1к10";
  if (numericLevel >= 9) return "1к8";
  if (numericLevel >= 2) return "1к6";
  return null;
}

export function getSpellPersonalHint(spell, derived, slotLevel = spell?.level) {
  const id = spell?.id;
  const level = Number(slotLevel);
  const characterLevel = Number(derived?.level ?? 1);
  const scaling = (base, step, die, threshold) => {
    const count = base + (characterLevel >= 17 ? 3 : characterLevel >= 11 ? 2 : characterLevel >= 5 ? 1 : 0);
    return `${count}к${die} (уровень персонажа ${threshold})`;
  };
  if (id === "vicious-mockery-2014") {
    return `Урон: ${scaling(1, 1, 4, "1/5/11/17")}.`;
  }
  if (id === "mind-sliver-2014") {
    return `Урон: ${scaling(1, 1, 6, "1/5/11/17")}.`;
  }
  if (id === "healing-word-2014" && Number.isInteger(level) && level >= 1) {
    return `Лечение: ${level}к4 ${derived?.abilityModifiers?.charisma >= 0 ? "+" : "−"} ${Math.abs(Number(derived?.abilityModifiers?.charisma ?? 0))} (модификатор Харизмы).`;
  }
  if (id === "dissonant-whispers-2014" && Number.isInteger(level) && level >= 1) {
    return `Урон: ${level + 2}к6.`;
  }
  if (id === "spray-of-cards-2014" && Number.isInteger(level) && level >= 2) {
    return `Урон: ${level}к10.`;
  }
  if (id === "raulothims-psychic-lance-2014" && Number.isInteger(level) && level >= 4) {
    return `Урон: ${level + 3}к6.`;
  }
  if (id === "synaptic-static-2014") return "Урон: 8к6 независимо от выбранной ячейки.";
  if (id === "minor-illusion-2014" && spell?.source === "racial") {
    return "Расовый заговор наследия Малболга; базовая характеристика — Харизма.";
  }
  if (id === "disguise-self-2014" && spell?.source === "racial") {
    return "Расовое наложение 2 круга · 1 применение после долгого отдыха.";
  }
  if (id === "invisibility-2014" && spell?.source === "racial") {
    return "Расовое наложение 2 круга · только на себя · 1 применение после долгого отдыха.";
  }
  if (id === "counterspell-2014" || id === "dispel-magic-2014") {
    const check = Number(derived?.abilityChecks?.charisma);
    const formatted = Number.isFinite(check) ? `${check >= 0 ? "+" : ""}${check}` : "—";
    return `Проверка Харизмы ${formatted}; СЛ = 10 + уровень отменяемого заклинания.`;
  }
  return null;
}

